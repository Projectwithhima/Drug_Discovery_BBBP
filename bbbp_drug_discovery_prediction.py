def compute_comprehensive_descriptors(smiles_list):
    """Compute comprehensive molecular descriptors"""
    descriptors_list = []
    valid_smiles = []

    print("Computing molecular descriptors...")

    for i, smiles in enumerate(smiles_list):
        if i % 500 == 0 and i > 0:
            print(f"  Processed {i} molecules...")

        smiles_str = str(smiles).strip()
        mol = Chem.MolFromSmiles(smiles_str)

        if mol is not None:
            try:
                desc = {
                    'MolWt': Descriptors.MolWt(mol),
                    'LogP': Descriptors.MolLogP(mol),
                    'TPSA': Descriptors.TPSA(mol),
                    'HAcceptors': Lipinski.NumHAcceptors(mol),
                    'HDonors': Lipinski.NumHDonors(mol),
                    'RotatableBonds': Lipinski.NumRotatableBonds(mol),
                    'AromaticRings': Lipinski.NumAromaticRings(mol),
                    'FractionCSP3': rdMolDescriptors.CalcFractionCSP3(mol),
                    'HeavyAtomCount': mol.GetNumHeavyAtoms(),
                    'RingCount': Lipinski.RingCount(mol),
                    'QED': QED.qed(mol),
                    'NumHeteroatoms': rdMolDescriptors.CalcNumHeteroatoms(mol),
                }

                desc['CNS_MPO_Score'] = (
                    (1 if desc['LogP'] <= 3 else 0) +
                    (1 if desc['TPSA'] <= 60 else 0) +
                    (1 if desc['HDonors'] <= 1 else 0) +
                    (1 if desc['HAcceptors'] <= 6 else 0) +
                    (1 if desc['MolWt'] <= 360 else 0)
                )

                desc['MolecularFlexibility'] = (desc['RotatableBonds'] / desc['HeavyAtomCount']
                                               if desc['HeavyAtomCount'] > 0 else 0)
                desc['PolarSurfaceAreaRatio'] = (desc['TPSA'] / desc['MolWt']
                                                if desc['MolWt'] > 0 else 0)

                violations = 0
                if desc['MolWt'] > 500: violations += 1
                if desc['LogP'] > 5: violations += 1
                if desc['HDonors'] > 5: violations += 1
                if desc['HAcceptors'] > 10: violations += 1
                desc['LipinskiViolations'] = violations
                desc['DrugLikeness'] = max(0, 5 - violations) / 5.0

                descriptors_list.append(desc)
                valid_smiles.append(smiles_str)

            except Exception as e:
                continue

    print(f"  Successfully computed descriptors for {len(descriptors_list)} molecules")
    return pd.DataFrame(descriptors_list), valid_smiles

