def perform_scaffold_split(df, smiles_column, test_size=0.2, random_state=42):
    """Performs Bemis-Murcko scaffold splitting on a DataFrame."""

    scaffold_to_indices = {}
    scaffold_less_indices = []

    # 1. Iterate through each SMILES string and generate scaffolds
    for idx, smiles in df[smiles_column].items():
        mol = Chem.MolFromSmiles(str(smiles))
        if mol is None:
            scaffold_less_indices.append(idx)
            continue

        try:
            # Correct function call for Bemis-Murcko scaffold
            scaffold = MurckoScaffold.GetScaffoldForMol(mol)
            # Ensure the scaffold is not None and has at least one atom (i.e., not an empty scaffold)
            if scaffold is None or scaffold.GetNumAtoms() == 0:
                scaffold_less_indices.append(idx)
                continue

            scaffold_smiles = Chem.MolToSmiles(scaffold)
            if scaffold_smiles not in scaffold_to_indices:
                scaffold_to_indices[scaffold_smiles] = []
            scaffold_to_indices[scaffold_smiles].append(idx)
        except Exception as e:
            scaffold_less_indices.append(idx)
            continue

    unique_scaffolds = list(scaffold_to_indices.keys())

    if not unique_scaffolds:
        # If no scaffolds were found for any molecule, perform a simple train_test_split
        print("Warning: No unique scaffolds found. Performing standard train_test_split.")
        all_indices = list(df.index)
        train_indices, test_indices = train_test_split(
            all_indices, test_size=test_size, random_state=random_state
        )
    else:
        # Split unique scaffolds into train and test sets
        # Ensure there are enough scaffolds to split based on test_size
        if len(unique_scaffolds) * test_size < 1:
            # If test_size would result in less than 1 test scaffold, assign at least one to test
            # Or, if unique_scaffolds is very small, adjust test_size dynamically or just take one for test
            test_scaffold_count = max(1, int(len(unique_scaffolds) * test_size))
            if test_scaffold_count == len(unique_scaffolds): # Avoid 100% test set if only one unique scaffold
                test_scaffold_count = len(unique_scaffolds) - 1 if len(unique_scaffolds) > 1 else 1
            current_test_size = test_scaffold_count / len(unique_scaffolds)
            print(f"Adjusting test_size for scaffolds to {current_test_size:.2f} due to small number of unique scaffolds.")
        else:
            current_test_size = test_size

        train_scaffolds, test_scaffolds = train_test_split(
            unique_scaffolds, test_size=current_test_size, random_state=random_state
        )

        train_indices = []
        for scaffold_smiles in train_scaffolds:
            train_indices.extend(scaffold_to_indices[scaffold_smiles])

        test_indices = []
        for scaffold_smiles in test_scaffolds:
            test_indices.extend(scaffold_to_indices[scaffold_smiles])

        # Add scaffold-less compounds to train and test sets, maintaining ratio
        if scaffold_less_indices:
            train_scaffold_less, test_scaffold_less = train_test_split(
                scaffold_less_indices, test_size=test_size, random_state=random_state
            )
            train_indices.extend(train_scaffold_less)
            test_indices.extend(test_scaffold_less)

    df_train = df.loc[train_indices].reset_index(drop=True)
    df_test = df.loc[test_indices].reset_index(drop=True)

    print(f"Original dataset size: {len(df)}")
    print(f"Training set size: {len(df_train)}")
    print(f"Test set size: {len(df_test)}")
    print(f"Number of unique scaffolds found: {len(unique_scaffolds)}")
    print(f"Scaffold-less compounds: {len(scaffold_less_indices)}")

    return df_train, df_test

