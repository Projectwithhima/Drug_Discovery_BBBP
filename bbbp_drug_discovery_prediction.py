# Define GCN model with dropout for regularization
# ===============================
class MolecularGCN(nn.Module):
    def __init__(self, num_features, hidden_dim=128, output_dim=1, dropout=0.3):
        super(MolecularGCN, self).__init__()
        self.conv1 = GCNConv(num_features, hidden_dim)
        self.conv2 = GCNConv(hidden_dim, hidden_dim)
        self.fc1 = nn.Linear(hidden_dim, hidden_dim//2)
        self.fc2 = nn.Linear(hidden_dim//2, output_dim)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x, edge_index, batch):
        x = F.relu(self.conv1(x, edge_index))
        x = self.dropout(x)
        x = F.relu(self.conv2(x, edge_index))
        x = global_mean_pool(x, batch)
        x = F.relu(self.fc1(x))
        x = self.dropout(x)
        x = self.fc2(x)
        return torch.sigmoid(x)

# ===============================
# SMOTE / Weighted loss for skewed labels
# ===============================
def compute_class_weights(labels):
    """Return weights for imbalanced binary classes"""
    labels = torch.tensor(labels, dtype=torch.float)
    pos_weight = (len(labels) - labels.sum()) / labels.sum()
    return pos_weight

# ===============================
#  Prepare Graph Data (SMILES to Graph)
# ===============================
def smiles_to_graph(smiles):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None

    atom_features = []
    for atom in mol.GetAtoms():
        feature = [
            atom.GetAtomicNum(),
            atom.GetDegree(),
            atom.GetFormalCharge(),
            int(atom.GetChiralTag()),
            int(atom.GetIsAromatic()),
            atom.GetMass(),
        ]
        atom_features.append(feature)

    atom_features = torch.tensor(atom_features, dtype=torch.float)

    edge_indices = []
    for bond in mol.GetBonds():
        i = bond.GetBeginAtomIdx()
        j = bond.GetEndAtomIdx()
        edge_indices.append([i, j])
        edge_indices.append([j, i])

    if len(edge_indices) == 0:
        edge_index = torch.tensor([[0], [0]], dtype=torch.long)
    else:
        edge_index = torch.tensor(edge_indices, dtype=torch.long).t().contiguous()

    return Data(x=atom_features, edge_index=edge_index)

def prepare_graph_data(smiles_list, labels=None):
    data_list = []
    valid_indices = []

    for i, smiles in enumerate(smiles_list):
        graph_data = smiles_to_graph(smiles)
        if graph_data is not None:
            if labels is not None:
                graph_data.y = torch.tensor([labels[i]], dtype=torch.float)
            data_list.append(graph_data)
            valid_indices.append(i)
    return data_list, valid_indices

